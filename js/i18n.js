let INFO_TIP_SEQ=0;
function ligaInfoPopups(){
  document.querySelectorAll('.hint:not(.hintpop)').forEach(h=>{
    if(h.id || h.classList.contains('filaviso')) return;
    const conteudo=h.innerHTML.trim();
    if(!conteudo) return;
    const id='tip_'+(++INFO_TIP_SEQ);
    h.classList.add('hintpop');
    h.innerHTML=`<button type="button" class="tipbtn" aria-label="${htmlEsc(tr('infoTipLabel'))}" aria-describedby="${id}">?</button>
      <span class="tipbox" id="${id}" role="tooltip">${conteudo}</span>`;
  });
}
